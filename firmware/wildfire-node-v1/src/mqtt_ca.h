// mqtt_ca.h -- the TLS trust anchor for the MQTT uplink (task 0099 item 7b).
//
// The broker (mqtt.nordtronics.io:8883) serves a Let's Encrypt chain whose
// served file ends at ISRG Root X2 cross-signed by ISRG Root X1. The
// cross-signed file therefore does NOT anchor its own chain, and pinning it
// fails the handshake. The self-signed ISRG Root X1 is the anchor that
// terminates the chain (backend/DEPLOY.md), so that is what is pinned here --
// no setInsecure(), no trust-on-first-use.
//
// This is a PUBLIC root certificate (it ships in every OS trust store); it is
// not a credential and carries no site-specific value.
//
// identity : CN=ISRG Root X1, O=Internet Security Research Group, C=US
// self-signed, valid 2015-06-04 .. 2035-06-04
// sha256   : 96:BC:EC:06:26:49:76:F3:74:60:77:9A:CF:28:C5:A7:
//            CF:E8:A3:C0:AA:E1:1A:8F:FC:EE:05:C0:BD:DF:08:C6
// source   : Mozilla CA store (system ca-bundle), cross-checked against
//            /usr/share/ca-certificates/mozilla/ISRG_Root_X1.crt as named by
//            backend/DEPLOY.md.
//
// NOTE: certificate-validity checking is on (CONFIG_MBEDTLS_HAVE_TIME_DATE), so
// this anchor cannot validate at the 1970 default clock -- the image must set
